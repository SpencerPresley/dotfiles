#!/usr/bin/env python3
"""Render the Claude Code settings JSON Schema into local reference files.

Fetches the authoritative Claude Code settings schema from SchemaStore (the same
one a settings.json "$schema" line points editors at) and writes two files:

  <ref_out>   Annotated .jsonc — every user-level key with its type, enum values,
              default, and full description as comments. NOT valid JSON: a lookup
              sheet, not a live config.
  <skel_out>  Minimal valid settings.json seed (just the "$schema" line), which is
              what turns on editor autocomplete for every key.

Enterprise/admin ("managed settings") keys are filtered out — they're noise in a
user-level config. Existing output files are left untouched if the fetch or parse
fails, so a network blip can't clobber a good reference.

Usage: cc-settings-ref.py <ref_out> <skel_out> [--url URL]
Wrapped by the cc-settings-ref zsh function; runnable standalone for testing.
"""
import argparse
import json
import sys
import urllib.request

DEFAULT_URL = "https://json.schemastore.org/claude-code-settings.json"

# Substrings that mark a key as enterprise/admin-only in its description.
MANAGED = ("managed settings", "admin", "(windows managed", "managed setting")


def resolve(value, defs):
    """Follow a one-level $ref into the schema's definitions, else return as-is."""
    if isinstance(value, dict) and "$ref" in value:
        return defs.get(value["$ref"].split("/")[-1], {})
    return value


def render_reference(schema, url):
    """Return (jsonc_text, key_count) for the annotated user-level reference."""
    props = schema.get("properties", {})
    defs = schema.get("definitions", schema.get("$defs", {}))

    lines = [
        "// Claude Code settings.json — annotated reference (user-level keys only)",
        f"// Source: {url}",
        "// Generated by cc-settings-ref. Has comments => NOT valid JSON: a lookup",
        "// sheet, not a live config. Copy keys you want into a real settings.json.",
        "{",
        f'  "$schema": "{url}",',
        "",
    ]

    count = 0
    for key, spec in props.items():
        if key == "$schema":
            continue
        desc = (spec.get("description") or "").replace("\n", " ").strip()
        if any(m in desc.lower() for m in MANAGED):
            continue

        target = resolve(spec, defs)
        enum = spec.get("enum") or target.get("enum")
        typ = spec.get("type") or target.get("type") or ("enum" if enum else "?")
        default = spec.get("default", target.get("default", "—"))

        # Render enum/default as JSON literals (true, "latest", []) rather than
        # Python reprs (True, 'latest') — this is a JSON reference, after all.
        tag = f"type={typ}"
        if enum:
            tag += f" enum={json.dumps(enum)}"
        tag += f" default={json.dumps(default)}" if default != "—" else " default=—"

        lines += [f"  // [{tag}]", f"  // {desc}", f'  "{key}":  ,', ""]
        count += 1

    lines.append("}")
    return "\n".join(lines) + "\n", count


def main():
    ap = argparse.ArgumentParser(
        description="Render the Claude Code settings schema into reference files."
    )
    ap.add_argument("ref_out", help="path for the annotated .jsonc reference")
    ap.add_argument("skel_out", help="path for the minimal valid settings.json seed")
    ap.add_argument("--url", default=DEFAULT_URL, help="settings schema URL")
    args = ap.parse_args()

    try:
        with urllib.request.urlopen(args.url, timeout=20) as resp:
            schema = json.load(resp)
    except Exception as exc:  # network error, non-JSON, etc.
        print(
            f"cc-settings-ref: failed to fetch/parse schema from {args.url}: {exc}",
            file=sys.stderr,
        )
        return 1

    reference, count = render_reference(schema, args.url)

    # Only write after a successful fetch+parse, so failures never clobber.
    with open(args.ref_out, "w") as f:
        f.write(reference)
    with open(args.skel_out, "w") as f:
        f.write(json.dumps({"$schema": args.url}, indent=2) + "\n")

    print(count)
    return 0


if __name__ == "__main__":
    sys.exit(main())
